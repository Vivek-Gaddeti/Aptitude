/* Build the small data file that pages load for the dashboard and the Ctrl+K finder:
     data/progress.js  window.PROGRESS = { catalog, learn, qcount, gens }
       catalog  the CATALOG (sections > topics > patterns, titles only)
       learn    { quant: [{id,title,group}], ... } sections that have lesson content
       qcount   { "quant/percentages/successive-change": 15, ... } bank questions per pattern
       gens     ["quant/percentages/successive-change", ...] patterns that have a generator file loaded
   Usage:  node tools/lite.js      (then python tools/pages.py && node tools/stamp.js)                       */
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, ".."), data = path.join(root, "data");
global.window = global; global.R = String.raw;   // no document: qbank.js must run without a DOM
require(path.join(root, "assets/site.js"));

const load = (f) => { try { new Function(fs.readFileSync(f, "utf8"))(); return true; } catch (e) { console.log("  skipped " + path.relative(root, f) + ": " + e.message); return false; } };
const walk = (d) => (fs.existsSync(d) ? fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : /\.js$/.test(e.name) ? [path.join(d, e.name)] : [])) : []).sort();

load(path.join(data, "catalog.js"));
// qbank.js adds the helpers some generator files call at load time; it is optional here
const qb = path.join(root, "assets/qbank.js");
if (fs.existsSync(qb)) load(qb);
if (fs.existsSync(path.join(data, "briefs.js"))) load(path.join(data, "briefs.js"));
// every lesson file: data/learn/<sec>.js and data/learn/<sec>-<n>.js (several agents write one file each)
const learnDir = path.join(data, "learn");
if (fs.existsSync(learnDir)) fs.readdirSync(learnDir).filter((f) => f.endsWith(".js")).sort().forEach((f) => load(path.join(learnDir, f)));
["q", "sets", "gen"].forEach((d) => walk(path.join(data, d)).forEach(load));

const sec = (s) => ({ id: s.id, title: s.title, group: s.group });
const catalog = CATALOG.map((c) => ({ sec: c.sec, name: c.name, short: c.short, page: c.page,
  topics: c.topics.map((t) => ({ id: t.id, title: t.title, group: t.group, patterns: t.patterns.map((p) => ({ id: p.id, title: p.title })) })) }));
const learn = {}; Object.keys(LEARN).forEach((k) => (learn[k] = LEARN[k].map(sec)));
const qcount = {}; QB.qs.forEach((q) => { const k = q.sec + "/" + q.topic + "/" + q.pattern; qcount[k] = (qcount[k] || 0) + 1; });
const progress = { catalog, learn, qcount, gens: Object.keys(QB.gens || {}) };
fs.mkdirSync(data, { recursive: true });
fs.writeFileSync(path.join(data, "progress.js"), "/* generated by tools/lite.js — do not edit. Titles of everything plus question counts, for the dashboard and the Ctrl+K finder. */\nwindow.PROGRESS = " + JSON.stringify(progress) + ";\n");
const topics = CATALOG.reduce((n, c) => n + c.topics.length, 0), pats = CATALOG.reduce((n, c) => n + c.topics.reduce((m, t) => m + t.patterns.length, 0), 0);
console.log(`data/progress.js written: ${topics} topics, ${pats} patterns, ${QB.qs.length} bank questions, ${Object.keys(QB.gens || {}).length} generators, ${Object.values(learn).reduce((n, a) => n + a.length, 0)} learn sections`);
if (SITE.ring.total !== topics) console.log(`  note: SITE.ring.total is ${SITE.ring.total}, there are ${topics} topics (catalog.js corrects it at load time)`);
